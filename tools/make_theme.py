"""Builds src/NetworkProfiles.App/Themes/DarkRed.xaml: overrides for WPF's Fluent dark theme in the LTC-MTC palette
(near-black surfaces, one red accent).

The Fluent theme builds its brushes from colours with StaticResource, so overriding a colour alone changes nothing;
every brush that uses an overridden colour has to be re-declared. This script finds those brushes in WPF's own
Dark.xaml and writes them out with the new colours, so the list stays complete when WPF adds controls.

Usage: python3 tools/make_theme.py Dark.xaml src/NetworkProfiles.App/Themes/DarkRed.xaml
Dark.xaml is https://github.com/dotnet/wpf/blob/release/10.0/src/Microsoft.DotNet.Wpf/src/Themes/
PresentationFramework.Fluent/Resources/Theme/Dark.xaml (use the branch matching the app's .NET version).
"""
import re
import sys
import xml.etree.ElementTree as ET

# LTC-MTC Theme.cs: Background 0c0c0e, Card 151517, Border 2a2a2f, Primary d6323d, Signal ef4b55.
COLORS = {
    # Accent. Dark-theme controls fill with Light2 and write accent text with Light3/Light2.
    "SystemAccentColor": "#FFD6323D",
    "SystemAccentColorLight1": "#FFE03E48",
    "SystemAccentColorLight2": "#FFD6323D",
    "SystemAccentColorLight3": "#FFEF4B55",
    "SystemAccentColorDark1": "#FFB82A34",
    "SystemAccentColorDark2": "#FF9A222B",
    "SystemAccentColorDark3": "#FF7C1B22",
    # White text on red; Fluent dark uses black, which suits its light-blue accent but not red.
    "TextOnAccentFillColorPrimary": "#FFFFFFFF",
    "TextOnAccentFillColorSecondary": "#CCFFFFFF",
    # Surfaces.
    "ApplicationBackgroundColor": "#FF0C0C0E",
    "SolidBackgroundFillColorBase": "#FF0C0C0E",
    "SolidBackgroundFillColorSecondary": "#FF151517",
    "SolidBackgroundFillColorTertiary": "#FF1C1C1F",
    "CardBackgroundFillColorDefault": "#FF151517",
    "CardBackgroundFillColorSecondary": "#FF1C1C1F",
    "CardStrokeColorDefault": "#FF2A2A2F",
    "CardStrokeColorDefaultSolid": "#FF2A2A2F",
    "SurfaceStrokeColorDefault": "#FF2A2A2F",
}

NS = "http://schemas.microsoft.com/winfx/2006/xaml/presentation"
X = "http://schemas.microsoft.com/winfx/2006/xaml"
KEY = f"{{{X}}}Key"
REF = re.compile(r"^\{(?:Static|Dynamic)Resource (\w+)\}$")


def local(tag):
    return tag.split("}", 1)[-1]


def uses_override(el):
    return any((m := REF.match(v)) and m.group(1) in COLORS for e in el.iter() for v in e.attrib.values())


def substitute(el):
    for e in el.iter():
        for name, value in e.attrib.items():
            if (m := REF.match(value)) and m.group(1) in COLORS:
                e.attrib[name] = COLORS[m.group(1)]
            elif value.startswith("{StaticResource "):
                # Other colours stay Fluent's. They live in another dictionary, which a StaticResource here
                # might not see when this one loads; a DynamicResource is resolved later, from the app.
                e.attrib[name] = value.replace("{StaticResource ", "{DynamicResource ", 1)


def to_xaml(el):
    """Serialises one element in XAML's usual prefixes (ElementTree would invent its own)."""
    attrs = "".join(f' {"x:Key" if k == KEY else k}="{v}"' for k, v in el.attrib.items())
    children = "".join(to_xaml(c) for c in el)
    tag = local(el.tag)
    return f"<{tag}{attrs}>{children}</{tag}>" if children else f"<{tag}{attrs} />"


def main(src, dst):
    root = ET.parse(src).getroot()
    out = [f'    <Color x:Key="{k}">{v}</Color>' for k, v in COLORS.items()]
    brushes = 0
    for el in root:
        if local(el.tag).endswith("Brush") and KEY in el.attrib and uses_override(el):
            substitute(el)
            out.append("    " + to_xaml(el))
            brushes += 1
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""<!-- Generated by tools/make_theme.py from WPF's Fluent Dark.xaml; edit the colours there, not here.
     Re-declares {brushes} Fluent brushes with the LTC-MTC palette: near-black surfaces, one red accent. -->
<ResourceDictionary xmlns="{NS}"
                    xmlns:x="{X}">
""" + "\n".join(out) + "\n</ResourceDictionary>\n")
    print(f"{len(COLORS)} colours, {brushes} brushes -> {dst}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
